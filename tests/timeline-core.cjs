'use strict';
const assert=require('node:assert/strict');
const T=require('../web/timeline-core.js');
const track={property:'x',keyframes:[{time_ms:0,value:0,easing:'linear'},{time_ms:1000,value:100},{time_ms:2000,value:0}]};
assert.equal(T.valueAt(track,0),0);
assert.equal(T.valueAt(track,500),50);
assert.equal(T.valueAt(track,1000),100);
assert.equal(T.valueAt(track,1500),50);
assert.equal(T.valueAt(track,2000),0);
assert.equal(T.timelineTime(2250,2000,'loop'),250);
assert.equal(T.timelineTime(2250,2000,'once'),2000);
assert.equal(T.timelineTime(2250,2000,'pingpong'),1750);
assert.equal(T.timelineTime(-250,2000,'loop'),1750);
assert.equal(T.valueAt({keyframes:[{time_ms:0,value:1,easing:'step'},{time_ms:100,value:3}]},99),1);
assert.equal(T.valueAt({keyframes:[{time_ms:0,value:1,easing:'step'},{time_ms:100,value:3}]},100),3);
assert.equal(T.valueAt({keyframes:[{time_ms:0,value:0,easing:'smooth'},{time_ms:100,value:100}]},50),50);
assert.deepEqual(T.layerAt({x:20,opacity:.5,tracks:[track]},500,2000,'loop').x,50);
assert.deepEqual(T.validateTracks([track],2000,[],'valid'),[]);
assert.ok(T.validateTracks([track,track],2000,[],'duplicate').length);
assert.ok(T.validateTracks([{property:'opacity',keyframes:[{time_ms:0,value:1.5}]}],2000,[],'opacity').length);
assert.ok(T.validateTracks([{property:'x',keyframes:[{time_ms:1000,value:1},{time_ms:500,value:2}]}],2000,[],'unordered').length);
assert.ok(T.validateTracks([{property:'rotation_deg',keyframes:[{time_ms:2100,value:1}]}],2000,[],'duration').length);
console.log('Keyframe timeline interpolation, loop, step, smooth, validation: PASS');
